import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { chromium } from 'playwright';
const extension=resolve('.output/chrome-mv3');
const manifest=JSON.parse(await readFile(join(extension,'manifest.json'),'utf8'));
const dir=await mkdtemp(join(tmpdir(),'offer-popup-'));
await mkdir('artifacts/popup',{recursive:true});
let ctx;
try{
 ctx=await chromium.launchPersistentContext(dir,{channel:'chromium',headless:true,colorScheme:'light',viewport:{width:384,height:650},args:[`--disable-extensions-except=${extension}`,`--load-extension=${extension}`, '--no-sandbox']});
 const worker=ctx.serviceWorkers()[0]??await ctx.waitForEvent('serviceworker',{timeout:20000});
 const id=new URL(worker.url()).host;
 const page=await ctx.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`chrome-extension://${id}/${manifest.action.default_popup}`);
 await page.getByRole('button',{name:'Switch to dark mode',exact:true}).waitFor();
 await page.getByRole('button',{name:'Official offer',exact:true}).waitFor();
 await page.screenshot({path:'artifacts/popup/offer-light.png',fullPage:true});
 assert.equal(await page.locator('html').evaluate(el=>el.classList.contains('dark')),false);
 await page.getByRole('button',{name:'Switch to dark mode',exact:true}).click();
 await page.waitForFunction(()=>document.documentElement.classList.contains('dark'));
 await page.getByRole('button',{name:'Switch to light mode',exact:true}).waitFor();
 await page.waitForFunction(()=>!document.documentElement.dataset.beuiVt);
 assert.equal(await page.locator('html').evaluate(el=>getComputedStyle(el).getPropertyValue('--background').trim()),'#151515');
 await page.screenshot({path:'artifacts/popup/offer-dark.png',fullPage:true});
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 await page.locator('#workspace').fill('Synthetic workspace');
 assert.equal(await page.locator('#workspace').inputValue(),'Synthetic workspace');
 await page.locator('#seats').fill('8');
 await page.getByRole('button',{name:'Increase seats',exact:true}).click();
 assert.equal(await page.locator('#seats').inputValue(),'9');
 const sw=page.getByRole('switch',{name:'Remember billing after link succeeds'});
 await sw.click();assert.equal(await sw.getAttribute('aria-checked'),'true');
 await page.screenshot({path:'artifacts/popup/settings-dark.png',fullPage:true});
 await page.getByRole('button',{name:'Back to offer',exact:true}).click();
 assert.equal(await page.locator('#settings-view').isVisible(),false);
 await page.reload();
 await page.getByRole('button',{name:'Switch to light mode',exact:true}).waitFor();
 assert.equal(await page.locator('html').evaluate(el=>el.classList.contains('dark')),true);
 assert.deepEqual(errors,[]);
 console.log('Built extension popup: theme persistence, navigation, inputs and switch passed.');
}finally{await ctx?.close();await rm(dir,{recursive:true,force:true});}
